/** JSON Schema's string length (P7): code points, the count antd's own "emoji as length 1" demo swaps in. */
const codePointCount = (text: string) => Array.from(text).length

/**
 * One control per field kind (spec §6.3): string → Input, enum → Radio.Group, boolean → Switch, number or integer →
 * InputNumber. A bounded string counts and cuts in code points through antd's `count` (antd doc Input, CountConfig and
 * the "Custom count logic" demo), where the native `maxLength` would count UTF-16 units. InputNumber takes the full
 * width through the Dify inputs form's class (antd 6.6.5 InputNumber has no `block`), and `precision` 0 for an
 * integer. Option labels are the values as text.
 */
const fieldControl = (field: FlatField) => {
	switch (field.type) {
		case 'string':
			return (
				<Input
					count={
						field.maxLength === undefined
							? undefined
							: {
									show: true,
									max: field.maxLength,
									strategy: codePointCount,
									exceedFormatter: (text, { max }) => Array.from(text).slice(0, max).join(''),
								}
					}
				/>
			)
		case 'number':
		case 'integer':
			return (
				<InputNumber
					className={formStyles.number}
					min={field.minimum}
					max={field.maximum}
					precision={field.type === 'integer' ? 0 : undefined}
				/>
			)
		case 'boolean':
			return <Switch />
		case 'enum':
			return <Radio.Group options={field.options.map(value => ({ label: String(value), value }))} />
	}
}

interface AnswerProps {
	interrupt: Interrupt
	answers: TurnAnswers
}

/**
 * The bordered box of the tool card's approval (approval-actions.tsx; AI Elements' `Confirmation`): the agent's message
 * above, the buttons at its end, negative first and the primary one last (Reject then Approve there; Cancel then
 * Submit, No then Yes here). An antd Card `size="small"` (`antd info Card --version 6.6.5`). The box holds only what the
 * user acts on (the owner, 2026-10-15: "the border should only be for the button like the tool").
 */
function ActionBox({ message, children }: { message?: string; children: ReactNode }) {
	return (
		<Card size="small">
			<Flex
				vertical
				gap="small"
			>
				{message && <RequestMessage>{message}</RequestMessage>}
				<Flex
					gap="small"
					justify="end"
					align="center"
					wrap
				>
					{children}
				</Flex>
			</Flex>
		</Card>
	)
}

/**
 * The flat-schema form (P7): one Form.Item per field, labelled by its title or name, its description as help text,
 * `required` marked by its rules (antd doc Form.Item `required`: "generated by the validation rule"), with no border of
 * its own, as a tool card's arguments; then the action box with the message, Cancel and Submit (the submit button stays
 * inside the Form, antd's `htmlType="submit"`). Submit sends the payload, Cancel the `cancelled` status. The Form's `disabled` reaches every control and button inside it (antd doc
 * Form `disabled`).
 */
function InterruptForm({ interrupt, answers, fields }: AnswerProps & { fields: FlatField[] }) {
	const { t } = useTranslation()
	// antd builds each field's id from the Form's `name` (`${name}_${field}`, antd `es/form/util.js` getFieldId) and asks
	// for a different `name` per form on one page (antd doc Form, FAQ); an interrupt id is the agent's string, so the
	// name comes from React's useId ("unique IDs that can be passed to accessibility attributes", react.dev `useId`).
	const name = useId()
	return (
		<Form
			name={name}
			layout="vertical"
			initialValues={initialValuesOf(fields)}
			disabled={answers.disabled}
			onFinish={(values: Record<string, unknown>) =>
				answers.answer({
					kind: 'resume',
					interruptId: interrupt.id,
					status: 'resolved',
					payload: payloadOf(fields, values),
				})
			}
		>
			{fields.map(field => (
				<Form.Item
					key={field.name}
					name={field.name}
					label={field.title ?? field.name}
					extra={field.description}
					rules={fieldRules(field, t)}
					// antd doc Form.Item `valuePropName`: "the prop of Switch or Checkbox is `checked`".
					valuePropName={field.type === 'boolean' ? 'checked' : 'value'}
				>
					{fieldControl(field)}
				</Form.Item>
			))}
			<ActionBox message={interrupt.message}>
				<Button
					onClick={() =>
						answers.answer({ kind: 'resume', interruptId: interrupt.id, status: 'cancelled' })
					}
				>
					{t('shared_chat.interrupt.cancel')}
				</Button>
				<Button
					type="primary"
					htmlType="submit"
				>
					{t('shared_chat.interrupt.submit')}
				</Button>
			</ActionBox>
		</Form>
	)
}

/**
 * The card's actions (interruptCardView): the decision as the approval's DecisionNote with Change (plan call P13), in
 * the box under the message and a form's values as the answered card shows them, Dismiss, or the answer the kind
 * allows.
 */
function InterruptAnswer({ interrupt, answers }: AnswerProps) {
	const { t } = useTranslation()
	const view = interruptCardView(interrupt, answers.draft, answers.now)
	const { disabled } = answers
	const resolve = (payload: Record<string, unknown> | boolean) =>
		answers.answer({ kind: 'resume', interruptId: interrupt.id, status: 'resolved', payload })
	const cancel = () =>
		answers.answer({ kind: 'resume', interruptId: interrupt.id, status: 'cancelled' })
	switch (view.kind) {
		case 'decided': {
			// The card reads as it will once the answer went (answer-record.tsx), with Change in the box. A decided view
			// has its entry (interruptCardView), read by own key: an interrupt id is the agent's string.
			const recorded = Object.hasOwn(answers.draft.resume, interrupt.id)
				? answers.draft.resume[interrupt.id]
				: undefined
			const { values } = answeredReceipt({
				interrupt,
				status: recorded?.status ?? 'cancelled',
				payload: recorded?.payload,
			})
			return (
				<AnswerRecord
					message={interrupt.message}
					values={values}
					payload={recorded?.payload}
				>
					<DecisionNote
						itemId={interrupt.id}
						color={draftTagColor(view.tagKey)}
						label={t(view.tagKey)}
					/>
				</AnswerRecord>
			)
		}
		case 'expired':
			return (
				<ActionBox message={interrupt.message}>
					<Button
						disabled={disabled}
						onClick={cancel}
					>
						{t('shared_chat.answer.dismiss')}
					</Button>
				</ActionBox>
			)
		case 'form':
			return (
				<InterruptForm
					interrupt={interrupt}
					answers={answers}
					fields={view.fields}
				/>
			)
		case 'confirm':
			return (
				<ActionBox message={interrupt.message}>
					<Button
						disabled={disabled}
						onClick={() => resolve(false)}
					>
						{t('shared_chat.interrupt.no')}
					</Button>
					<Button
						type="primary"
						disabled={disabled}
						onClick={() => resolve(true)}
					>
						{t('shared_chat.interrupt.yes')}
					</Button>
				</ActionBox>
			)
		case 'approval':
			return (
				<ActionBox message={interrupt.message}>
					<Button
						disabled={disabled}
						onClick={() => resolve(approvalPayload(interrupt.responseSchema, false))}
					>
						{t('shared_chat.answer.reject')}
					</Button>
					<Button
						type="primary"
						disabled={disabled}
						onClick={() => resolve(approvalPayload(interrupt.responseSchema, true))}
					>
						{t('shared_chat.answer.approve')}
					</Button>
				</ActionBox>
			)
		case 'cancel':
			return (
				<ActionBox message={interrupt.message}>
					<Button
						disabled={disabled}
						onClick={cancel}
					>
						{t('shared_chat.interrupt.cancel')}
					</Button>
				</ActionBox>
			)
	}
}

/**
 * An interrupt that is not a gated call on screen (spec §6.3; plan calls P6, P8, P13, P14), as the chat's card in the
 * turn (chat-card.tsx), held open: the user must see it to answer. Its header: an icon by how it is answered
 * (chat-card-view.ts `interruptIcon`), the title from its reason (the three core reasons localised, any other as sent)
 * and "Waiting for you", or "Expired" once its `expiresAt` has passed. Its body as a tool card's: a form's fields with
 * no border, then the bordered box (ActionBox) with its message and the answer at its end: Cancel and Submit for a
 * flat schema, No and Yes for a confirmation without one, Reject and Approve for an approval whose call has no tool part
 * in the turn, Cancel alone otherwise, and Dismiss once expired; a drafted decision as the answered card shows it
 * (answer-record.tsx), with Change in the box. Every card has a
 * way out (decision 50). The answers come from the turn's TurnAnswersContext (React `use`); an interrupt that is not
 * open there shows its title and message only. Every agent string renders as text.
 */
export default function InterruptCard({ interrupt }: { interrupt: Interrupt }) {
	const { t } = useTranslation()
	const context = use(TurnAnswersContext)
	const answers = context?.open.interrupts.some(open => open.id === interrupt.id) ? context : null
	const titleKey = interruptTitleKey(interrupt.reason)
	return (
		<ChatCard
			fixed="open"
			icon={INTERRUPT_ICONS[interruptIcon(interrupt)]}
			title={titleKey ? t(titleKey) : interrupt.reason}
			badge={answers ? cardBadge(openInterruptBadge(interrupt, answers.now), t) : undefined}
		>
			{answers ? (
				<InterruptAnswer
					interrupt={interrupt}
					answers={answers}
				/>
			) : (
				interrupt.message && <RequestMessage>{interrupt.message}</RequestMessage>
			)}
		</ChatCard>
	)
}
